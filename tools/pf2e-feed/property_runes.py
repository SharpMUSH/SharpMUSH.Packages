"""Writes the property rune tables in pf2e/package.yaml from a Foundry pf2e checkout.

Foundry keeps property runes in code (src/module/item/physical/runes.ts), not in its packs, so the feed does not carry
them. This reads WEAPON_PROPERTY_RUNES and ARMOR_PROPERTY_RUNES with node, names them from static/lang/en.json, and
replaces the lines between the "property runes" markers on the core object: DATA`RUNE`W`<SLUG> for a weapon's,
DATA`RUNE`A`<SLUG> for armor's, keyed by Foundry's slug in capitals, each one JSON object.

  python3 -I tools/pf2e-feed/property_runes.py foundry pf2e/package.yaml

A weapon rune's JSON: slug, name, level, price (gp), rarity, traits; dice (type, n, die, cat, crit, pred, mod), notes
(on attack or damage, out, pred, title, text), ignore (resistances it ignores), dos (degree adjustments: pred, from,
to), adds (traits its Strikes gain) and other (what is left to the GM). Armor runes carry no mechanics in Foundry,
only what they are worth.
"""
import json, re, subprocess, sys, os, tempfile

BEGIN = "      # --- property runes: generated by tools/pf2e-feed/property_runes.py, do not edit ---\n"
END = "      # --- end of property runes ---\n"


def literal(src, name):
	i = src.index("= {", src.index("const " + name)) + 2
	depth = 0
	for j in range(i, len(src)):
		if src[j] == "{":
			depth += 1
		elif src[j] == "}":
			depth -= 1
			if depth == 0:
				return src[i:j + 1]


def replace_arrays(text, key, convert):
	out, i = "", 0
	while True:
		k = text.find(key + ": [", i)
		if k < 0:
			return out + text[i:]
		j = text.index("[", k)
		depth = 0
		for e in range(j, len(text)):
			if text[e] == "[":
				depth += 1
			elif text[e] == "]":
				depth -= 1
				if depth == 0:
					break
		out += text[i:k] + key + ": " + json.dumps(convert(text[j:e + 1]))
		i = e + 1


def strike_adjustments(body):
	if "range" in body:
		return ["!Doubles the range increment."]
	return re.findall(r'traits\.(?:value\.)?push\("([a-z-]+)"\)', body)


def load(foundry):
	src = open(os.path.join(foundry, "src/module/item/physical/runes.ts"), encoding="utf-8").read()
	weapon = replace_arrays(literal(src, "WEAPON_PROPERTY_RUNES"), "strikeAdjustments", strike_adjustments)
	weapon = replace_arrays(weapon, "            adjustments", lambda b: ["!Critical specialization effects of picks are doubled."])
	weapon = weapon.replace("new Predicate(", "(")
	armor = literal(src, "ARMOR_PROPERTY_RUNES")
	with tempfile.TemporaryDirectory() as tmp:
		path = os.path.join(tmp, "runes.js")
		open(path, "w").write("module.exports={w:" + weapon + ",a:" + armor + "};")
		out = subprocess.run(["node", "-e", "process.stdout.write(JSON.stringify(require(process.argv[1])))", path],
			capture_output=True, text=True, check=True).stdout
	return json.loads(out)


def lang(en, key):
	node = en
	for part in key.split("."):
		node = node.get(part, {}) if isinstance(node, dict) else {}
	return node if isinstance(node, str) else key


OUTCOMES = {"criticalFailure": 0, "failure": 1, "success": 2, "criticalSuccess": 3}


def weapon_entry(en, rune):
	damage, attack = rune.get("damage", {}), rune.get("attack", {})
	out = {"slug": rune["slug"], "name": lang(en, rune["name"] + ""), "level": rune["level"], "price": rune["price"],
		"rarity": rune["rarity"], "traits": rune["traits"]}
	dice = []
	for d in damage.get("additional", []):
		if "modifier" in d:
			dice.append({"type": d["damageType"], "mod": d["modifier"], "cat": d.get("damageCategory") or d.get("category") or "",
				"pred": d.get("predicate") or []})
		else:
			dice.append({"type": d.get("damageType", ""), "n": d.get("diceNumber", 1), "die": int(d.get("dieSize", "d6")[1:]),
				"cat": d.get("category") or "", "crit": bool(d.get("critical")), "pred": d.get("predicate") or []})
	notes = [{"on": on, "out": [OUTCOMES[o] for o in n.get("outcome", [])], "pred": n.get("predicate") or [],
		"title": lang(en, n["title"]), "text": lang(en, n["text"])}
		for on, source in (("attack", attack), ("damage", damage)) for n in source.get("notes", [])]
	dos = [{"pred": a.get("predicate") or [], "from": OUTCOMES[k], "to": OUTCOMES[v["amount"]]}
		for a in attack.get("dosAdjustments", []) for k, v in a["adjustments"].items()]
	adjust = rune.get("strikeAdjustments", []) + damage.get("adjustments", [])
	for key, value in (("dice", dice), ("notes", notes), ("dos", dos),
		("ignore", [r["type"] for r in damage.get("ignoredResistances", [])]),
		("adds", [a for a in adjust if not a.startswith("!")]), ("other", [a[1:] for a in adjust if a.startswith("!")])):
		if value:
			out[key] = value
	return out


def armor_entry(en, rune):
	return {"slug": rune["slug"], "name": lang(en, rune["name"]), "level": rune["level"], "price": rune["price"],
		"rarity": rune["rarity"], "traits": rune["traits"]}


def quote(value):
	return "'" + json.dumps(value, ensure_ascii=False, separators=(",", ":")).replace("'", "''") + "'"


def main(argv):
	foundry, package = argv[1], argv[2]
	runes = load(foundry)
	en = json.load(open(os.path.join(foundry, "static/lang/en.json"), encoding="utf-8"))
	lines = []
	for kind, table, entry in (("W", runes["w"], weapon_entry), ("A", runes["a"], armor_entry)):
		for rune in sorted(table.values(), key=lambda r: r["slug"]):
			value = entry(en, rune)
			lines.append(f"      DATA`RUNE`{kind}`{value['slug'].upper()}: {quote(value)}\n")
	text = open(package, encoding="utf-8").read()
	start, stop = text.index(BEGIN) + len(BEGIN), text.index(END)
	open(package, "w", encoding="utf-8").write(text[:start] + "".join(lines) + text[stop:])
	print(f"{len(runes['w'])} weapon and {len(runes['a'])} armor property runes")


if __name__ == "__main__":
	main(sys.argv)
