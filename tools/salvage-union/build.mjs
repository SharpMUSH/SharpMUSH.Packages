// Builds the data object of sheet-salvage-union/package.yaml from the compendiums of the Salvage Union
// (Unofficial) Foundry VTT system, https://gitlab.com/pacosgrove1/salvage-union-foundry-vtt-unofficial.
//
//   git clone https://gitlab.com/pacosgrove1/salvage-union-foundry-vtt-unofficial.git /tmp/su-foundry
//   git -C /tmp/su-foundry checkout <FOUNDRY_COMMIT>
//   npm ci && node build.mjs /tmp/su-foundry
//
// It rewrites the lines between the "generated" markers in sheet-salvage-union/package.yaml and nothing else.
// The compendium text is Salvage Union Core Book text, which the Salvage Union Open Game Licence 1.0b lets
// virtual tabletop content copy word for word; see sheet-salvage-union/NOTICE.md.

import { ClassicLevel } from 'classic-level';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const FOUNDRY_COMMIT = 'a1e47b514cda2af5ed423bce1c08523e8d235ae9'; // v1.3.0

const here = path.dirname(fileURLToPath(import.meta.url));
const target = path.resolve(here, '../../sheet-salvage-union/package.yaml');
const BEGIN = '  # ---- generated by tools/salvage-union/build.mjs: begin';
const END = '  # ---- generated by tools/salvage-union/build.mjs: end';

const foundry = process.argv[2];
if (!foundry) {
	console.error('usage: node build.mjs <foundry checkout>');
	process.exit(2);
}
try {
	const head = execFileSync('git', ['-C', foundry, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
	if (head !== FOUNDRY_COMMIT) {
		console.error(`${foundry} is at ${head}; this build reads ${FOUNDRY_COMMIT}.`);
		process.exit(1);
	}
} catch {
	console.error(`${foundry} is not a git checkout of the Foundry system.`);
	process.exit(1);
}

async function pack(name) {
	// Copied first: LevelDB takes a lock on the directory it opens.
	const copy = fs.mkdtempSync(path.join(os.tmpdir(), `su-${name}-`));
	fs.cpSync(path.join(foundry, 'packs', name), copy, { recursive: true });
	fs.rmSync(path.join(copy, 'LOCK'), { force: true });
	const db = new ClassicLevel(copy, { valueEncoding: 'json' });
	const rows = [];
	for await (const [key, value] of db.iterator()) rows.push({ key, ...value });
	await db.close();
	fs.rmSync(copy, { recursive: true, force: true });
	return rows;
}

// ---- text -------------------------------------------------------------------------------------------------

const ENTITIES = { nbsp: ' ', amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", times: 'x', rsquo: "'", lsquo: "'", rdquo: '"', ldquo: '"', ndash: '-', mdash: '-', hellip: '...', deg: ' degrees', sect: '§' };

function entities(text) {
	return text
		.replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n)))
		.replace(/&#x([0-9a-f]+);/gi, (_, n) => String.fromCodePoint(parseInt(n, 16)))
		.replace(/&([a-z]+);/gi, (m, n) => ENTITIES[n.toLowerCase()] ?? m);
}

// HTML to plain text: one paragraph a line, list items "- ", links and table references by their label. Curly
// quotes, dashes and the multiplication sign become ASCII, so a client without UTF-8 reads the same text.
function plain(html) {
	if (!html) return '';
	let text = String(html)
		.replace(/@(?:UUID|DisplayTable|Compendium)\[[^\]]*\]\{([^}]*)\}/g, '$1')
		.replace(/@(?:UUID|DisplayTable|Compendium)\[[^\]]*\]/g, '')
		.replace(/\[\[\/r[^\]]*\]\]/g, '')
		.replace(/<li[^>]*>/gi, '\n- ')
		.replace(/<\/(p|div|h\d|li|tr|ul|ol|table)>/gi, '\n')
		.replace(/<br\s*\/?>/gi, '\n')
		.replace(/<[^>]+>/g, '');
	text = entities(text)
		.replace(/[‘’‚′]/g, "'")
		.replace(/[“”„″]/g, '"')
		.replace(/[–—−]/g, '-')
		.replace(/×/g, 'x')
		.replace(/…/g, '...')
		.replace(/ /g, ' ');
	return text
		.split('\n')
		.map(line => line.replace(/[ \t]+/g, ' ').trim())
		.filter(line => line.length)
		.join('\n');
}

// A name as a key: upper case letters, digits and hyphens, at most 30 characters.
function key(name) {
	return plain(name)
		.toUpperCase()
		.replace(/[^A-Z0-9]+/g, '-')
		.replace(/^-+|-+$/g, '')
		.slice(0, 30)
		.replace(/-+$/g, '');
}

function words(list) {
	return list.filter(Boolean).join(' ');
}

const TECH = value => String(value ?? '').replace(/^T/i, '') || '1';
const ACTIONS = { t: 'turn', s: 'short', l: 'long', f: 'free', r: 'reaction', p: 'passive', d: 'downtime' };

// ---- attributes ---------------------------------------------------------------------------------------------

const attributes = [];
function set(name, value) {
	const text = String(value ?? '').replace(/\r/g, '');
	if (!text.length) return;
	if (text.includes('{{') || text.includes('}}')) throw new Error(`${name} holds a package reference`);
	attributes.push([name, text]);
}

function items(rows) {
	return rows.filter(row => row.key.startsWith('!items!') && row.type);
}

function tableKey(id, tables) {
	const match = /tables\.([A-Za-z0-9]+)$/.exec(id || '');
	return match ? tables.get(match[1])?.key ?? '' : '';
}

// Hot (n): the heat one use adds. Hot (X) and Hot (1d20) are left to the player.
function hot(traits) {
	for (const trait of traits ?? []) {
		const match = /^Hot \((\d+)\)$/i.exec(trait.trim());
		if (match) return match[1];
	}
	return '';
}

const tableRows = await pack('tables');
const tables = new Map();
for (const row of tableRows.filter(r => r.key.startsWith('!tables!'))) {
	tables.set(row._id, { ...row, key: key(row.name.replace(/ Table$/, '')), results: [] });
}
for (const row of tableRows.filter(r => r.key.startsWith('!tables.results!'))) {
	tables.get(row.key.split('!')[2].split('.')[0])?.results.push(row);
}
const tableNames = new Map([...tables.values()].map(t => [plain(t.name).toLowerCase(), t.key]));

// ---- classes, trees and abilities ------------------------------------------------------------------------------
// The class rules are the Core Book's (Pilot Bay: Gaining Abilities, and each class): a core class's three trees,
// each leading to one advancement, its Advanced tree or a Hybrid Class; the Salvager draws on every core tree and
// never advances. Foundry has no class items, so these are written here; the trees and their abilities come
// from the compendium's folders.
const CLASSES = {
	ENGINEER: { label: 'Engineer', paths: { 'MECH-TECH': 'ADVANCED-ENGINEER', FORGING: 'FABRICATOR', 'MECHANICAL-KNOWLEDGE': 'UNION-REP' } },
	HACKER: { label: 'Hacker', paths: { HACKING: 'ADVANCED-HACKER', ELECTRONICS: 'FABRICATOR', AUGMENTATION: 'CYBORG' } },
	HAULER: { label: 'Hauler', paths: { TRADING: 'ADVANCED-HAULER', SALVAGING: 'SMUGGLER', LEADERSHIP: 'UNION-REP' } },
	SALVAGER: { label: 'Salvager', paths: {} },
	SCOUT: { label: 'Scout', paths: { RECON: 'ADVANCED-SCOUT', SLEUTH: 'SMUGGLER', SNIPER: 'RANGER' } },
	SOLDIER: { label: 'Soldier', paths: { 'TACTICAL-WARFARE': 'ADVANCED-SOLDIER', 'GLADITORIAL-COMBAT': 'CYBORG', SURVIVALIST: 'RANGER' } },
};
const HYBRIDS = {
	FABRICATOR: ['FORGING', 'ELECTRONICS'],
	'UNION-REP': ['LEADERSHIP', 'MECHANICAL-KNOWLEDGE'],
	CYBORG: ['AUGMENTATION', 'GLADITORIAL-COMBAT'],
	RANGER: ['SURVIVALIST', 'SNIPER'],
	SMUGGLER: ['SLEUTH', 'SALVAGING'],
};

const abilityRows = await pack('abilities');
const folders = new Map(abilityRows.filter(r => r.key.startsWith('!folders!')).map(r => [r._id, r]));
const trees = new Map();
const abilities = [];
for (const item of items(abilityRows).sort((a, b) => a.sort - b.sort)) {
	if (!item.system?.level) continue; // the compendium's placeholders for an ability's own gear
	const folder = folders.get(item.folder);
	const owner = folders.get(folder.folder);
	const group = folders.get(owner.folder).name; // Core Classes or Hybrid Classes
	const ownerKey = key(owner.name);
	let tree;
	let tier;
	if (folder.name === 'Legendary') {
		tree = `LEGENDARY-${ownerKey}`;
		tier = 'legendary';
	} else if (folder.name === 'Advanced' && group.startsWith('Hybrid')) {
		tree = ownerKey;
		tier = 'hybrid';
	} else if (folder.name === 'Advanced') {
		tree = `ADVANCED-${ownerKey}`;
		tier = 'advanced';
	} else {
		tree = key(folder.name);
		tier = 'core';
	}
	const label = tier === 'legendary' ? `Legendary ${owner.name}` : tier === 'advanced' ? `Advanced ${owner.name}` : tier === 'hybrid' ? owner.name : folder.name;
	if (!trees.has(tree)) trees.set(tree, { label, tier, owner: ownerKey, abilities: [] });
	const entry = trees.get(tree);
	const abilityKey = key(item.name);
	if (abilities.some(a => a.key === abilityKey)) throw new Error(`two abilities called ${abilityKey}`);
	entry.abilities.push(abilityKey);
	abilities.push({ key: abilityKey, item, tree, tier, level: tier === 'legendary' ? 0 : entry.abilities.length });
}

for (const [name, cls] of Object.entries(CLASSES)) {
	const core = name === 'SALVAGER' ? [...trees].filter(([, t]) => t.tier === 'core').map(([k]) => k) : Object.keys(cls.paths);
	for (const tree of [...core, ...Object.values(cls.paths)]) if (!trees.has(tree)) throw new Error(`${name}: no tree ${tree}`);
	set(`CLASS\`${name}`, cls.label);
	set(`CLASS\`${name}\`TREES`, words(core));
	set(`CLASS\`${name}\`PATHS`, words(Object.entries(cls.paths).map(([from, to]) => `${from}:${to}`)));
	set(`CLASS\`${name}\`MAX`, name === 'SALVAGER' ? 12 : 10);
}
for (const [tree, entry] of trees) {
	set(`TREE\`${tree}`, entry.label);
	set(`TREE\`${tree}\`TIER`, entry.tier);
	set(`TREE\`${tree}\`ABILITIES`, words(entry.abilities));
	if (entry.tier === 'advanced' || entry.tier === 'hybrid') set(`TREE\`${tree}\`LEGENDARY`, `LEGENDARY-${entry.owner}`);
	if (entry.tier === 'hybrid') {
		if (!HYBRIDS[tree]) throw new Error(`no hybrid rule for ${tree}`);
		set(`TREE\`${tree}\`ADDS`, words(HYBRIDS[tree]));
	}
}
for (const { key: k, item, tree, tier, level } of abilities) {
	const s = item.system;
	set(`ABILITY\`${k}`, plain(item.name));
	set(`ABILITY\`${k}\`TREE`, tree);
	set(`ABILITY\`${k}\`TIER`, tier);
	set(`ABILITY\`${k}\`LEVEL`, level);
	set(`ABILITY\`${k}\`AP`, String(s.ap ?? '').trim().toUpperCase());
	set(`ABILITY\`${k}\`ACTION`, ACTIONS[s.action] ?? '');
	set(`ABILITY\`${k}\`RANGE`, s.range);
	set(`ABILITY\`${k}\`TABLE`, tableKey(s.table_id, tables));
	set(`ABILITY\`${k}\`TEXT`, plain(s.description));
}

// ---- mech parts and pilot equipment ---------------------------------------------------------------------------

const lists = { CHASSIS: [], SYSTEM: [], MODULE: [], EQUIPMENT: [] };
function part(prefix, item) {
	const s = item.system;
	const k = key(item.name);
	if (lists[prefix].includes(k)) throw new Error(`two ${prefix} called ${k}`);
	lists[prefix].push(k);
	set(`${prefix}\`${k}`, plain(item.name));
	set(`${prefix}\`${k}\`TECH`, TECH(s.techLevel));
	return [k, s];
}
for (const item of items(await pack('chassis'))) {
	const [k, s] = part('CHASSIS', item);
	set(`CHASSIS\`${k}\`SP`, s.sp);
	set(`CHASSIS\`${k}\`EP`, s.ep);
	set(`CHASSIS\`${k}\`HEAT`, s.heat);
	set(`CHASSIS\`${k}\`SYSTEMS`, s.systemSlots);
	set(`CHASSIS\`${k}\`MODULES`, s.moduleSlots);
	set(`CHASSIS\`${k}\`CARGO`, s.cargo);
	set(`CHASSIS\`${k}\`VALUE`, s.salvageValue);
	set(`CHASSIS\`${k}\`TEXT`, plain(s.description));
}
for (const [prefix, packName] of [['SYSTEM', 'systems'], ['MODULE', 'modules']]) {
	for (const item of items(await pack(packName))) {
		const [k, s] = part(prefix, item);
		set(`${prefix}\`${k}\`SLOTS`, s.slots);
		set(`${prefix}\`${k}\`VALUE`, s.salvageValue);
		set(`${prefix}\`${k}\`EP`, String(s.ep ?? '').trim().toUpperCase());
		set(`${prefix}\`${k}\`HOT`, hot(s.traits));
		set(`${prefix}\`${k}\`RANGE`, s.range);
		set(`${prefix}\`${k}\`DAMAGE`, s.damage);
		set(`${prefix}\`${k}\`TRAITS`, (s.traits ?? []).join('|'));
		set(`${prefix}\`${k}\`ACTION`, ACTIONS[s.action] ?? '');
		set(`${prefix}\`${k}\`USES`, s.uses?.max || '');
		set(`${prefix}\`${k}\`TABLE`, tableKey(s.table_id, tables));
		set(`${prefix}\`${k}\`TEXT`, plain(s.description));
	}
}
for (const item of items(await pack('equipment'))) {
	if (item.system.inventorySlot !== true) continue; // an ability's own gear, on the ability
	const [k, s] = part('EQUIPMENT', item);
	set(`EQUIPMENT\`${k}\`AP`, String(s.ap ?? '').trim().toUpperCase());
	set(`EQUIPMENT\`${k}\`RANGE`, s.range);
	set(`EQUIPMENT\`${k}\`DAMAGE`, s.damage);
	set(`EQUIPMENT\`${k}\`TRAITS`, (s.traits ?? []).join('|'));
	set(`EQUIPMENT\`${k}\`USES`, s.uses?.max || '');
	set(`EQUIPMENT\`${k}\`TABLE`, tableKey(s.table_id, tables));
	set(`EQUIPMENT\`${k}\`TEXT`, plain(s.description));
}
const bays = [];
for (const item of items(await pack('crawler'))) {
	const k = key(item.name);
	bays.push(k);
	set(`BAY\`${k}`, plain(item.name));
	set(`BAY\`${k}\`TEXT`, plain(item.system.description));
}

// ---- NPCs ----------------------------------------------------------------------------------------------------
// The Core Book's NPCs, vehicles, drones and Bio-Titans, for encounters: NPC`<key> the name, with KIND (npc,
// vehicle, bio-titan or mech), GROUP (the compendium folder), HEALTH (hp or sp) and MAX, TECH and VALUE (the
// Tech Level and Salvage Value of what can be salvaged), TRAITS, TEXT and ACTIONS (1 2 3 ...), each action
// A`<n> with its KIND, DAMAGE, RANGE, TRAITS, ACTION and TEXT.
const npcs = [];
const npcRows = await pack('actors');
const npcFolders = new Map(npcRows.filter(r => r.key.startsWith('!folders!')).map(r => [r._id, plain(r.name)]));
const npcItems = new Map();
for (const row of npcRows.filter(r => r.key.startsWith('!actors.items!'))) {
	const owner = row.key.split('!')[2].split('.')[0];
	if (!npcItems.has(owner)) npcItems.set(owner, []);
	npcItems.get(owner).push(row);
}
const NPC_KINDS = { npc: 'npc', vehicle: 'vehicle', 'bio-titan': 'bio-titan', 'npc-mech': 'mech' };
for (const actor of npcRows.filter(r => r.key.startsWith('!actors!')).sort((a, b) => plain(a.name).localeCompare(plain(b.name)))) {
	const s = actor.system;
	const k = key(actor.name);
	if (npcs.includes(k)) throw new Error(`two NPCs called ${k}`);
	npcs.push(k);
	const kind = NPC_KINDS[actor.type];
	if (!kind) throw new Error(`${actor.name} is a ${actor.type}`);
	const health = actor.type === 'npc' ? (s.healthType === 'sp' ? 'sp' : 'hp') : 'sp';
	const meter = actor.type === 'npc' ? s.hp : s.sp;
	set(`NPC\`${k}`, plain(actor.name));
	set(`NPC\`${k}\`KIND`, kind);
	set(`NPC\`${k}\`GROUP`, npcFolders.get(actor.folder) ?? '');
	set(`NPC\`${k}\`HEALTH`, health);
	set(`NPC\`${k}\`MAX`, Math.max(Number(meter?.value) || 0, Number(meter?.max) || 0));
	if (s.techLevel) set(`NPC\`${k}\`TECH`, TECH(s.techLevel));
	set(`NPC\`${k}\`VALUE`, s.salvageValue ?? '');
	set(`NPC\`${k}\`TRAITS`, (s.traits ?? []).join('|'));
	set(`NPC\`${k}\`TEXT`, plain(s.description));
	const actions = (npcItems.get(actor._id) ?? []).sort((a, b) => (a.sort ?? 0) - (b.sort ?? 0) || plain(a.name).localeCompare(plain(b.name)));
	actions.forEach((item, i) => {
		const a = item.system;
		const n = i + 1;
		set(`NPC\`${k}\`A\`${n}`, plain(item.name));
		set(`NPC\`${k}\`A\`${n}\`KIND`, item.type === 'npc-ability' ? 'ability' : item.type);
		set(`NPC\`${k}\`A\`${n}\`DAMAGE`, a.damage);
		set(`NPC\`${k}\`A\`${n}\`RANGE`, a.range);
		set(`NPC\`${k}\`A\`${n}\`TRAITS`, (a.traits ?? []).join('|'));
		set(`NPC\`${k}\`A\`${n}\`ACTION`, ACTIONS[a.action] ?? '');
		set(`NPC\`${k}\`A\`${n}\`TEXT`, plain(a.description));
	});
	set(`NPC\`${k}\`ACTIONS`, words(actions.map((_, i) => String(i + 1))));
}

// ---- tables ---------------------------------------------------------------------------------------------------
// ROW`<low>-<high> each result. A result that only names another table (the callsign table's five lists) is
// stored as THEN, the table to roll next.
const tableKeys = [];
for (const table of [...tables.values()].sort((a, b) => a.key.localeCompare(b.key))) {
	if (!table.results.length) continue;
	if (tableKeys.includes(table.key)) throw new Error(`two tables called ${table.key}`);
	tableKeys.push(table.key);
	set(`TABLE\`${table.key}`, plain(table.name).replace(/ Table$/, ''));
	set(`TABLE\`${table.key}\`TEXT`, plain(table.description));
	const rows = [];
	for (const result of table.results.sort((a, b) => a.range[0] - b.range[0])) {
		const low = result.range[0];
		const high = Math.min(result.range[1], 20);
		const text = plain(result.text);
		const then = tableNames.get(text.toLowerCase());
		const leaf = `TABLE\`${table.key}\`ROW\`${low}-${high}`;
		rows.push(`${low}-${high}`);
		set(leaf, then ? '' : text);
		if (then) set(`${leaf}\`THEN`, then);
	}
	set(`TABLE\`${table.key}\`ROWS`, words(rows));
}

for (const [prefix, list] of Object.entries(lists)) set(`LIST\`${prefix}`, words(list.sort()));
set('LIST`ABILITY', words(abilities.map(a => a.key).sort()));
set('LIST`TABLE', words(tableKeys));
set('LIST`BAY', words(bays.sort()));
set('LIST`NPC', words(npcs));
set('LIST`CLASS', words(Object.keys(CLASSES)));
set('LIST`TREE', words([...trees.keys()].sort()));

// What a check can be made with, for the sheet's API`TRAITS: the bare die, then every ability, system and module
// that is not passive. An ability with no action is something the pilot has, not something rolled; a system
// with none is a weapon.
const traitList = [{ key: 'die', label: 'The die', group: 'die', always: true }];
const actionOf = new Map(attributes.filter(([name]) => name.endsWith('`ACTION')).map(([name, value]) => [name, value]));
const labelOf = new Map(attributes);
for (const prefix of ['ABILITY', 'SYSTEM', 'MODULE']) {
	const keys = prefix === 'ABILITY' ? abilities.map(a => a.key).sort() : lists[prefix];
	for (const k of keys) {
		const action = actionOf.get(`${prefix}\`${k}\`ACTION`) ?? '';
		if (action === 'passive' || (prefix === 'ABILITY' && !action)) continue;
		traitList.push({ key: `${prefix.toLowerCase()}-${k.toLowerCase()}`, label: labelOf.get(`${prefix}\`${k}`), group: prefix.toLowerCase(), always: false });
	}
}
set('TRAITS', JSON.stringify(traitList));

// ---- write ----------------------------------------------------------------------------------------------------

const lines = [
	BEGIN,
	`  # The Core Book's content, from the Salvage Union (Unofficial) Foundry VTT system ${FOUNDRY_COMMIT.slice(0, 7)}`,
	'  # (v1.3.0). Do not edit by hand: change build.mjs and run it again.',
	'  - ref: data',
	'    type: thing',
	'    name: Salvage Union Data',
	'    location: "{{sheet}}"',
	'    flags: [no_command]',
	'    attributes:',
];
for (const [name, value] of attributes) {
	lines.push(`      ${name}: |-`);
	for (const line of value.split('\n')) lines.push(`        ${line}`);
}
lines.push(END);

const yaml = fs.readFileSync(target, 'utf8').split('\n');
const begin = yaml.indexOf(BEGIN);
const end = yaml.indexOf(END);
if (begin < 0 || end < begin) throw new Error(`${target} has no generated markers`);
yaml.splice(begin, end - begin + 1, ...lines);
fs.writeFileSync(target, yaml.join('\n'));
console.log(`${attributes.length} attributes: ${abilities.length} abilities, ${trees.size} trees, ${lists.CHASSIS.length} chassis, ${lists.SYSTEM.length} systems, ${lists.MODULE.length} modules, ${lists.EQUIPMENT.length} equipment, ${tableKeys.length} tables, ${bays.length} bays, ${npcs.length} NPCs.`);
